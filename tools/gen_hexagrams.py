ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "apps", "iching", "hexagrams.h")


def main():
    nums = [n for row in KW for n in row]
    assert sorted(nums) == list(range(1, 65)), "文王卦序表不完整或有重复"
    assert len(NAMES) == 65 and len(READINGS) == 65

    rows = []
    for r, upper in enumerate(ORDER):
        for c, lower in enumerate(ORDER):
            num = KW[r][c]
            rows.append((num, CODE[upper], CODE[lower], NAMES[num], READINGS[num]))
    rows.sort()

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// 自动生成，请勿手改。生成脚本：tools/gen_hexagrams.py\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("struct Hexagram {\n")
        f.write("    uint8_t num;\n    uint8_t upper;\n    uint8_t lower;\n")
        f.write("    const char* name;\n    const char* reading;\n};\n\n")
        f.write("// 上/下卦编码：乾7 兑3 离5 震1 巽6 坎2 艮4 坤0\n")
        f.write("static const Hexagram HEXAGRAMS[64] = {\n")
        for num, up, lo, name, reading in rows:
            f.write(f'    {{{num}, {up}, {lo}, "{name}", "{reading}"}},\n')
        f.write("};\n\n")
        f.write("static const char* const TRIGRAM_NATURE[8] = {\n")
        f.write('    "地", "雷", "水", "泽", "山", "火", "风", "天",\n')
        f.write("};\n")
    print(f"已写入 {OUT}，共 {len(rows)} 卦")


if __name__ == "__main__":
    main()
